#!/usr/bin/env python3
"""Render the public bundle table and tutorial dependencies from sources.json."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
ARTIFACTS = ('spx-installer', 'spx-server', 'spx-ui', 'spx-sdk',
             'spx-python', 'spx-examples')


def render(manifest):
    rows = ['| Artifact | Version | Exact commit |', '| --- | --- | --- |']
    for name in ARTIFACTS:
        source = manifest['sources'][name]
        if not re.fullmatch(r'[0-9a-f]{40}', source['commit']):
            raise ValueError(f'{name} requires an immutable full commit SHA')
        rows.append(f"| `{name}` | `{source['version']}` | `{source['commit']}` |")
    return '\n'.join(rows)


def tutorial_requirements(manifest):
    lines = ['# Generated by scripts/render_release.py from sources.json; use Python 3.12.']
    for name in ('spx-sdk', 'spx-python'):
        version = manifest['sources'][name]['version'].removeprefix('v')
        lines.append(f"{name}=={version.replace('-rc.', 'rc')}")
    return '\n'.join(lines + ['PyYAML==6.0.3', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    manifest = json.loads((ROOT / 'sources.json').read_text(encoding='utf-8'))
    release_notes = ROOT / 'release-notes.md'
    current = release_notes.read_text(encoding='utf-8')
    pattern = r'(?<=<!-- release-bundle:start -->\n).*?(?=\n<!-- release-bundle:end -->)'
    if len(re.findall(pattern, current, re.S)) != 1:
        raise ValueError('Release notes must contain one bundle table marker pair')
    expected = re.sub(pattern, lambda _: render(manifest), current, flags=re.S)
    outputs = {release_notes: expected,
               ROOT / 'requirements-tutorials.txt': tutorial_requirements(manifest)}
    for path, content in outputs.items():
        if args.check:
            if path.read_text(encoding='utf-8') != content:
                raise SystemExit(f'Stale generated release content: {path.name}')
        else:
            path.write_text(content, encoding='utf-8')
    print('Release table and tutorial requirements match sources.json.')


if __name__ == '__main__':
    main()
