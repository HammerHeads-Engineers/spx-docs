#!/usr/bin/env python3
"""Render GitBook presentation metadata and schema wrappers from the pinned API export."""
import argparse
from copy import deepcopy
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC_SLUG = 'hammerheadsengineers-api'
API_TITLE = 'SPX Server API'
API_DESCRIPTION = ('SPX Server API v3 endpoints for health checks, version discovery '
                   'and authenticated access to the simulation system hierarchy.')
MODELS_DESCRIPTION = ('Validation response schemas for SPX Server API v3, including '
                      'HTTPValidationError and ValidationError fields.')
HTTP_METHODS = {'get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'}


def documented_spec(source):
    """Only add presentation tags; keep the released API contract and source pin intact."""
    spec = deepcopy(source)
    expected = [{'name': API_TITLE, 'x-page-description': API_DESCRIPTION}]
    if spec.get('tags') not in (None, [], expected):
        raise ValueError('Review API page grouping before replacing existing tags')
    spec['tags'] = expected
    for path in spec['paths'].values():
        for method, operation in path.items():
            if method in HTTP_METHODS:
                if operation.get('tags') not in (None, [], [API_TITLE]):
                    raise ValueError('Review existing operation tags before regrouping')
                operation['tags'] = [API_TITLE]
    return spec


def render_models(spec):
    """Wrap live GitBook schema blocks in an authored page with durable SEO metadata."""
    lines = ['---', 'description: >-', '  ' + MODELS_DESCRIPTION, '---', '', '# Models', '',
             'These are API response schemas, not device definitions from the SPX model library.', '',
             '<!-- Generated by scripts/render_openapi_docs.py; edit the renderer, not this file. -->', '']
    for name in spec.get('components', {}).get('schemas', {}):
        lines += [f'## The {name} object', '',
                  '{% openapi-schemas spec="' + SPEC_SLUG + '" schemas="' + name + '" grouped="false" %}',
                  '{% endopenapi-schemas %}', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source_path = ROOT / 'api-v3-reference/openapi.json'
    spec = documented_spec(json.loads(source_path.read_text(encoding='utf-8')))
    outputs = {source_path: json.dumps(spec, indent=2) + '\n',
               ROOT / 'api-v3-reference/models.md': render_models(spec)}
    for path, text in outputs.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != text:
                raise SystemExit(f'Stale OpenAPI presentation output: {path.relative_to(ROOT)}')
        else:
            path.write_text(text, encoding='utf-8')
    print('OK: OpenAPI page metadata and schema wrapper match the pinned export')


if __name__ == '__main__':
    main()
